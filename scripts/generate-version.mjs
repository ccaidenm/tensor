#!/usr/bin/env node
// Generates src/generated/version.ts from src-tauri/tauri.conf.json —
// the ONE source of truth for the app version (#97). The app package,
// the Cargo crate, and the About panel all read the same stamped value
// (the crate/package versions stay in lockstep with tauri.conf by the
// version-sync test). Run automatically via npm's predev/prebuild
// hooks (the generate-licenses pattern) — never hand-edit the output.
//
// The output file is force-tracked past .gitignore (the
// licenses.json/symbols-index.json precedent) so a fresh clone's
// typecheck passes without running the script first.

import { writeFile, mkdir, readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.join(__dirname, '..');
const CONF_PATH = path.join(ROOT, 'src-tauri/tauri.conf.json');
const OUTPUT_PATH = path.join(ROOT, 'src/generated/version.ts');

const conf = JSON.parse(await readFile(CONF_PATH, 'utf-8'));
const version = conf.version;
if (typeof version !== 'string' || !/^\d+\.\d+\.\d+/.test(version)) {
  console.error(`[generate-version] tauri.conf.json carries no valid semver version: ${JSON.stringify(version)}`);
  process.exit(1);
}

await mkdir(path.dirname(OUTPUT_PATH), { recursive: true });
await writeFile(
  OUTPUT_PATH,
  `// GENERATED by scripts/generate-version.mjs — do not edit.\n` +
  `// The single source of truth is src-tauri/tauri.conf.json's "version".\n` +
  `export const APP_VERSION = '${version}';\n`,
);
console.log(`[generate-version] stamped ${version}`);
